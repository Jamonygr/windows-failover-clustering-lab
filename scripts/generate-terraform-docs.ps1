<#
.SYNOPSIS
    Regenerates TERRAFORM.md and per-module README.md references with
    terraform-docs. Use -Check to fail on drift without writing.
#>
[CmdletBinding()]
param(
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$configPath = Join-Path $repoRoot '.terraform-docs.yml'

if (-not (Get-Command terraform-docs -ErrorAction SilentlyContinue)) {
    throw 'terraform-docs is required. See CONTRIBUTING.md for the toolchain.'
}

$script:driftedFiles = @()

function Write-TerraformDocumentation {
    param(
        [Parameter(Mandatory)][string]$ModulePath,
        [Parameter(Mandatory)][string]$OutputPath,
        [Parameter(Mandatory)][string]$Title
    )

    $generated = & terraform-docs markdown table --config $configPath $ModulePath
    if ($LASTEXITCODE -ne 0) {
        throw "terraform-docs failed for $ModulePath"
    }

    $header = @(
        "# $Title",
        '',
        '> Generated by scripts/generate-terraform-docs.ps1. Do not edit the tables manually.',
        ''
    )
    # Normalize to LF so Windows and Linux produce byte-equivalent references
    $text = ((($header + $generated) -join "`n") -replace "`r`n", "`n").TrimEnd("`n") + "`n"

    if ($Check) {
        $existing = if (Test-Path $OutputPath) {
            ((Get-Content -Path $OutputPath -Raw) -replace "`r`n", "`n")
        }
        else { '' }
        if ($existing -ne $text) {
            $script:driftedFiles += $OutputPath
        }
    }
    else {
        [System.IO.File]::WriteAllText($OutputPath, $text)
        Write-Host "wrote $OutputPath"
    }
}

Write-TerraformDocumentation -ModulePath $repoRoot `
    -OutputPath (Join-Path $repoRoot 'TERRAFORM.md') `
    -Title 'Terraform reference'

Get-ChildItem -Path (Join-Path $repoRoot 'modules') -Directory | Sort-Object Name | ForEach-Object {
    Write-TerraformDocumentation -ModulePath $_.FullName `
        -OutputPath (Join-Path $_.FullName 'README.md') `
        -Title "Terraform module: modules/$($_.Name)"
}

if ($Check -and $script:driftedFiles.Count -gt 0) {
    Write-Host 'Documentation drift detected in:' -ForegroundColor Red
    $script:driftedFiles | ForEach-Object { Write-Host "  $_" }
    throw 'Run ./scripts/generate-terraform-docs.ps1 and commit the results.'
}

Write-Host 'Terraform documentation is up to date.' -ForegroundColor Green
